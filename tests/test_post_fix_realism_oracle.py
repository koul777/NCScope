@pytest.mark.parametrize(
    "follow_up",
    [
        "앞서 작성한 대장의 내용을 다시 설명해 주십시오.",
        "방금 수용한 상대 입장을 다시 말씀해 주십시오.",
        "앞서 제시한 판정값을 다시 설명해 주십시오.",
        "발표에서 가장 중요하게 사용한 수치와 배정 기준을 다시 말씀해 주십시오.",
    ],
)
def test_answer_slot_reference_without_a_branch_remains_non_adaptive(
    follow_up: str,
) -> None:
    result = evaluate_question_realism(
        "상충하는 자료를 검토해 조정안을 발표해 주십시오.",
        method="발표면접",
        follow_ups=[follow_up],
        question_source="openai_api",
    )

    assert result["checks"]["answer_adaptive_follow_ups"] is False
    assert result["metrics"]["adaptive_follow_up_count"] == 0


