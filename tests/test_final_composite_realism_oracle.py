@pytest.mark.parametrize(
    ("case_id", "method", "question", "follow_ups"),
    COMPOSITE_V18_REALISM_CASES,
    ids=[row[0] for row in COMPOSITE_V18_REALISM_CASES],
)
def test_retained_v18_question_matches_composite_human_oracle(
    case_id: str,
    method: str,
    question: str,
    follow_ups: list[str],
) -> None:
    result = evaluate_question_realism(
        {"type": method, "question": question, "follow_ups": follow_ups, "question_source": "codex_cli"}
    )

    assert result["policy_version"] == "field-realism-v3.14"
    assert result["passed"] is True, (case_id, result["issues"])
    assert result["metrics"]["adaptive_follow_up_count"] >= 2
    assert result["checks"]["no_prescribed_answer"] is True
    if method != "직무지식면접":
        assert result["checks"]["concrete_scenario"] is True


